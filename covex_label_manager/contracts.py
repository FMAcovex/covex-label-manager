"""Small, local contracts. No network clients or infrastructure."""
from typing import Protocol, Any

METADATA_FIELDS=('product','family','type','country','language')
FILTER_FIELDS=('category','family','type','origin','customer','country','language','version','state','acquisition')

class LibraryRepository(Protocol):
    def library_records(self) -> list[dict[str, Any]]: ...
    def set_favorite(self, label_id: int, value: bool) -> None: ...
    def mark_recent(self, label_id: int, version_id: int) -> None: ...
    def set_label_metadata(self, label_id: int, values: dict[str,str], source_ref: str) -> None: ...
